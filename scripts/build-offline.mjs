/** Bundle JSX at build time and produce a complete, content-versioned offline cache. */
import { createHash } from 'node:crypto';
import { readFile, writeFile, readdir, stat } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import { collectSpeech, loadCurriculum } from './generate-audio.mjs';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const publicDirectory = join(root, 'public');
const sources = ['data.js', 'icons.jsx', 'fx.jsx', 'exercises.jsx', 'screens.jsx', 'progress.js', 'app.jsx'];
const sourceText = await Promise.all(sources.map(file => readFile(join(publicDirectory, file), 'utf8')));
const manifest = JSON.parse(await readFile(join(publicDirectory, 'audio/manifest.json'), 'utf8'));
const requiredSpeech = collectSpeech(loadCurriculum(sourceText[0]));
const missingSpeech = [...requiredSpeech].filter(([text, spoken]) => manifest.entries[text]?.text !== spoken).map(([text]) => text);
if (missingSpeech.length) {
  throw new Error('Missing Hebrew recordings. Run node scripts/generate-audio.mjs before building. First missing text: ' + missingSpeech[0]);
}
// Every referenced recording must be present in the checkout. Merely having an
// alias in manifest.json must never allow a deploy to omit its actual MP3.
const recordingUrls = new Set([...Object.values(manifest.entries), ...Object.values(manifest.prompts)].map(record => record.url));
await Promise.all([...recordingUrls].map(async url => {
  if (!/^\/audio\/[a-f0-9]{20}\.mp3$/.test(url)) throw new Error('Invalid recording path in the audio manifest: ' + url);
  try {
    const recording = await stat(join(publicDirectory, url.slice(1)));
    if (!recording.isFile() || recording.size < 128) throw new Error('Recording is empty.');
  } catch (error) { throw new Error('Missing Hebrew recording ' + url + '. Run node scripts/generate-audio.mjs.', { cause: error }); }
}));
await build({
  stdin: {
    contents: "import React from 'react';\nimport * as ReactDOM from 'react-dom/client';\n" + sourceText.join('\n'),
    loader: 'jsx',
    resolveDir: root,
    sourcefile: 'hebrew-heroes.jsx',
  },
  outfile: join(publicDirectory, 'game.js'),
  bundle: true,
  minify: true,
  legalComments: 'eof',
  format: 'iife',
  target: ['safari15'],
  define: { 'process.env.NODE_ENV': '"production"' },
});

async function filesUnder(directory) {
  const names = await readdir(join(publicDirectory, directory));
  const output = [];
  for (const name of names.sort()) {
    const relative = directory + '/' + name;
    if ((await stat(join(publicDirectory, relative))).isDirectory()) output.push(...await filesUnder(relative));
    else output.push('/' + relative);
  }
  return output;
}
const files = ['/hebrew-heroes.html', '/styles.css', '/game.js', '/offline.js', '/manifest.webmanifest',
  ...await filesUnder('audio'), ...await filesUnder('fonts'), ...await filesUnder('icons')];
const assets = await Promise.all(files.map(async url => {
  const contents = await readFile(join(publicDirectory, url.slice(1)));
  return { url, hash: createHash('sha256').update(contents).digest('hex'), size: contents.byteLength };
}));
const version = createHash('sha256').update(JSON.stringify(assets)).digest('hex').slice(0, 20);

const serviceWorker = String.raw`/* Generated by scripts/build-offline.mjs. Do not edit this file directly. */
const VERSION = '${version}';
const ASSETS = ${JSON.stringify(assets)};
const CACHE_PREFIX = 'hebrew-heroes-assets-';
const CACHE_NAME = CACHE_PREFIX + VERSION;
const READY_KEY = '/__hebrew_heroes_offline_ready__';
let preparation = null;
let state = { status: 'preparing', completed: 0, total: ASSETS.length, error: '', version: VERSION };

function message(port) { if (port) port.postMessage({ type: 'HH_OFFLINE', state }); }
async function publish(next) {
  state = { ...state, ...next };
  const clients = await self.clients.matchAll({ type: 'window', includeUncontrolled: true });
  clients.forEach(client => client.postMessage({ type: 'HH_OFFLINE', state }));
}
async function hashResponse(response) {
  const digest = await crypto.subtle.digest('SHA-256', await response.arrayBuffer());
  return Array.from(new Uint8Array(digest), byte => byte.toString(16).padStart(2, '0')).join('');
}
async function validAsset(cache, asset) {
  const response = await cache.match(asset.url);
  return !!response && response.ok && await hashResponse(response) === asset.hash;
}
async function verifyCache() {
  const cache = await caches.open(CACHE_NAME);
  // Presence of a marker alone is insufficient: quota pressure or Safari may
  // remove cached entries. Recheck every byte before showing the airplane badge.
  let completed = 0;
  for (const asset of ASSETS) {
    if (await validAsset(cache, asset)) completed += 1;
  }
  const complete = completed === ASSETS.length;
  if (!complete) await cache.delete(READY_KEY);
  return { complete, completed };
}
async function prepare() {
  if (preparation) return preparation;
  preparation = (async () => {
    const cache = await caches.open(CACHE_NAME);
    await cache.delete(READY_KEY);
    let completed = 0;
    await publish({ status: 'preparing', completed, error: '' });
    // Limit simultaneous downloads on tablet Wi-Fi. Hashes prevent a partially
    // updated deploy, error page or interrupted file from being marked complete.
    const queue = [...ASSETS];
    let failure;
    await Promise.all(Array.from({ length: 4 }, async () => {
      while (queue.length && !failure) {
        const asset = queue.shift();
        try {
          if (!await validAsset(cache, asset)) {
            const controller = new AbortController();
            const timeout = setTimeout(() => controller.abort(), 30000);
            try {
              const response = await fetch(asset.url, { cache: 'reload', credentials: 'same-origin', signal: controller.signal });
              if (!response.ok || await hashResponse(response.clone()) !== asset.hash) {
                throw new Error('A game file could not be verified: ' + asset.url);
              }
              await cache.put(asset.url, response);
            } finally { clearTimeout(timeout); }
          }
          completed += 1;
          await publish({ completed });
        } catch (error) { failure = error; }
      }
    }));
    if (failure) throw failure;
    const verified = await verifyCache();
    if (!verified.complete) throw new Error('Some game files were not saved. Please retry the download.');
    // Publishing ready is the final atomic step after all assets are present.
    await cache.put(READY_KEY, new Response(JSON.stringify({ version: VERSION, count: ASSETS.length })));
    await publish({ status: 'ready', completed: ASSETS.length, error: '' });
  })().catch(async error => {
    await publish({ status: 'error', error: error.message || 'Download interrupted. Connect to Wi-Fi and retry.' });
    throw error;
  }).finally(() => { preparation = null; });
  return preparation;
}
self.addEventListener('install', event => {
  // Do not skipWaiting: updates take effect after open games close, preserving
  // an active child's exercise and the previously complete offline cache.
  event.waitUntil(prepare());
});
self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    const verified = await verifyCache();
    if (!verified.complete) return;
    await self.clients.claim();
    // At activation the previous worker no longer has controlled game tabs.
    const names = await caches.keys();
    await Promise.all(names.filter(name => name.startsWith(CACHE_PREFIX) && name !== CACHE_NAME).map(name => caches.delete(name)));
    await publish({ status: 'ready', completed: ASSETS.length, error: '' });
  })());
});
self.addEventListener('message', event => {
  if (!['HH_STATUS', 'HH_PREPARE'].includes(event.data?.type)) return;
  const port = event.ports[0];
  event.waitUntil((async () => {
    try {
      if (preparation) { message(port); return; }
      const verified = await verifyCache();
      if (verified.complete) await publish({ status: 'ready', completed: ASSETS.length, error: '' });
      else if (event.data.type === 'HH_PREPARE') await prepare();
      else await publish({ status: 'error', completed: verified.completed, error: 'Offline files are missing. Connect to Wi-Fi and tap retry.' });
    } catch (error) {
      await publish({ status: 'error', error: error.message || 'Offline files could not be checked. Please retry.' });
    }
    message(port);
  })());
});

async function audioRange(request, response) {
  const range = request.headers.get('range');
  if (!range) return response;
  const data = await response.arrayBuffer();
  const match = /^bytes=(\d*)-(\d*)$/.exec(range);
  if (!match || (!match[1] && !match[2])) return new Response(null, { status: 416, headers: { 'Content-Range': 'bytes */' + data.byteLength } });
  let start = match[1] ? Number(match[1]) : Math.max(0, data.byteLength - Number(match[2]));
  let end = match[1] && match[2] ? Math.min(Number(match[2]), data.byteLength - 1) : data.byteLength - 1;
  if (start > end || start >= data.byteLength) return new Response(null, { status: 416, headers: { 'Content-Range': 'bytes */' + data.byteLength } });
  const headers = new Headers(response.headers);
  headers.set('Content-Range', 'bytes ' + start + '-' + end + '/' + data.byteLength);
  headers.set('Content-Length', String(end - start + 1));
  headers.set('Accept-Ranges', 'bytes');
  return new Response(data.slice(start, end + 1), { status: 206, headers });
}
self.addEventListener('fetch', event => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== self.location.origin) return;
  const navigation = request.mode === 'navigate' && ['/', '/hebrew-heroes.html'].includes(url.pathname);
  const path = navigation ? '/hebrew-heroes.html' : url.pathname;
  if (!navigation && !ASSETS.some(asset => asset.url === path)) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE_NAME);
    const response = await cache.match(path);
    if (response) return path.startsWith('/audio/') ? audioRange(request, response) : response;
    // Missing cache entries cause status to lose ready; they never silently
    // establish readiness through individual opportunistic network requests.
    if (state.status === 'ready') await publish({ status: 'error', error: 'An offline file is missing. Connect to Wi-Fi and tap retry.' });
    return fetch(request);
  })());
});
`;
await writeFile(join(publicDirectory, 'sw.js'), serviceWorker);
const bytes = assets.reduce((total, asset) => total + asset.size, 0);
console.log('Offline bundle: ' + assets.length + ' verified assets, ' + (bytes / 1024 / 1024).toFixed(2) + ' MiB, version ' + version + '.');
