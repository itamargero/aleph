import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { describe, expect, test, vi } from 'vitest';
import * as audio from '../scripts/generate-audio.mjs';

const execute = promisify(execFile);

describe('offline Hebrew recording generation', () => {
  test('uses the verified native Hebrew neural voice with a measured learning pace', () => {
    expect(audio.AUDIO_CONFIG).toMatchObject({ engine: 'edge-tts', voice: 'he-IL-HilaNeural', rate: '-15%' });
  });

  test('changing voice or pace cannot reuse a recording generated by the previous voice', () => {
    const first = audio.audioId('שָׁלוֹם');
    expect(first).toMatch(/^[a-f0-9]{20}$/);
    expect(first).toBe(audio.audioId('שָׁלוֹם'));
    expect(first).not.toBe(audio.audioId('שָׁלוֹם', { ...audio.AUDIO_CONFIG, voice: 'he-IL-AvriNeural' }));
    expect(first).not.toBe(audio.audioId('שָׁלוֹם', { ...audio.AUDIO_CONFIG, rate: '-10%' }));
  });

  test('missing audio validation tools fail before contacting the speech service', async () => {
    const temporary = await mkdtemp(join(tmpdir(), 'aleph-tool-test-'));
    try {
      await mkdir(join(temporary, 'public'));
      await writeFile(join(temporary, 'public/data.js'), 'window.WORDS = {};');
      vi.stubEnv('PATH', temporary);
      await expect(audio.generate({ root: temporary })).rejects.toThrow('ffmpeg and ffprobe');
    } finally {
      vi.unstubAllEnvs();
      await rm(temporary, { recursive: true, force: true });
    }
  });

  test('failed synthesis preserves the last manifest and its offline recordings', async () => {
    const temporary = await mkdtemp(join(tmpdir(), 'aleph-generation-test-'));
    try {
      const output = join(temporary, 'public/audio');
      await mkdir(output, { recursive: true });
      await writeFile(join(temporary, 'public/data.js'), 'window.WORDS = {};');
      const previous = JSON.stringify({ voice: 'previous', entries: {} });
      await writeFile(join(output, 'manifest.json'), previous);
      await writeFile(join(output, 'previous.mp3'), 'Previous offline recording');
      vi.stubEnv('EDGE_TTS_BIN', join(temporary, 'missing-edge-tts'));
      await expect(audio.generate({ root: temporary })).rejects.toThrow('needs edge-tts');
      expect(await readFile(join(output, 'manifest.json'), 'utf8')).toBe(previous);
      expect(await readFile(join(output, 'previous.mp3'), 'utf8')).toBe('Previous offline recording');
    } finally {
      vi.unstubAllEnvs();
      await rm(temporary, { recursive: true, force: true });
    }
  });

  test('accepts decodable audible speech and rejects a valid silent MP3 or corrupt recording', async () => {
    const temporary = await mkdtemp(join(tmpdir(), 'aleph-audio-test-'));
    try {
      const silent = join(temporary, 'silent.mp3');
      await execute('ffmpeg', ['-hide_banner', '-loglevel', 'error', '-f', 'lavfi', '-i', 'anullsrc=r=24000:cl=mono', '-t', '1', silent]);
      const corrupt = join(temporary, 'corrupt.mp3');
      await writeFile(corrupt, 'An error document that is not audio.'.repeat(100));
      const manifest = JSON.parse(await readFile(new URL('../public/audio/manifest.json', import.meta.url), 'utf8'));
      const spoken = new URL('../public' + manifest.entries['א'].url, import.meta.url).pathname;
      expect(await audio.validateAudio(spoken)).toBe(true);
      expect(await audio.validateAudio(silent)).toBe(false);
      expect(await audio.validateAudio(corrupt)).toBe(false);
      expect(await audio.validateAudio(join(temporary, 'missing.mp3'))).toBe(false);
    } finally { await rm(temporary, { recursive: true, force: true }); }
  });
});
